/*
 * The docs of the blocks for the `@blocks-schema` endpoint, as Volto's
 * `load-blocks-docs` module, plus the docs of the native elements of a Plate
 * document. Volto's loader (`@plone/registry`) only reads docs files that name
 * a `block`, so it drops the element docs of `@plone/plate`. This is a port of
 * Aurora's loader, which also reads them.
 *
 * A docs file documents a block (`block`, and optionally one of its
 * `variation`s), or one or more comma-separated native elements (`element`),
 * such as a Plate `callout`. `title` names an element, which has no
 * configuration with a title.
 */
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const DOCS_SUFFIX = '.block.md';
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/;

/*
 * Reads the `key: value` lines of a Markdown file's frontmatter.
 */
function parseFrontmatter(markdown) {
  const match = markdown.match(FRONTMATTER);
  if (!match) return {};
  return Object.fromEntries(
    match[1]
      .split(/\r?\n/)
      .map((line) => line.match(/^\s*([\w-]+)\s*:\s*(.*?)\s*$/))
      .filter(Boolean)
      .map(([, key, value]) => [key, value.replace(/^(['"])(.*)\1$/, '$2')]),
  );
}

function findFiles(dir, found = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      findFiles(fullPath, found);
    } else if (entry.isFile() && entry.name.endsWith(DOCS_SUFFIX)) {
      found.push(fullPath);
    }
  }
  return found;
}

/*
 * Finds the docs files in the given folders, in order. When two files
 * document the same block, variation or element, the last one wins, so
 * add-ons listed after core can replace its docs.
 */
function findBlocksDocs(paths) {
  const sources = new Map();
  const add = (key, source) => {
    sources.delete(key);
    sources.set(key, source);
  };

  for (const dir of paths) {
    for (const file of findFiles(dir)) {
      const { block, variation, element, title } = parseFrontmatter(
        fs.readFileSync(file, 'utf-8'),
      );
      if (block) {
        add(variation ? `${block}|${variation}` : block, {
          block,
          ...(variation ? { variation } : {}),
          path: file,
        });
      } else if (element) {
        for (const name of element.split(',').map((item) => item.trim())) {
          if (!name) continue;
          add(`element:${name}`, {
            element: name,
            ...(title ? { title } : {}),
            path: file,
          });
        }
      } else {
        // eslint-disable-next-line no-console
        console.warn(
          `[volto-plate] ${file} has no "block" or "element" in its frontmatter, ignoring it.`,
        );
      }
    }
  }
  return [...sources.values()];
}

/*
 * The code of a module that imports every docs file as a string, with the
 * `?raw` query that Volto's webpack configuration handles, and exports them
 * as a list.
 */
function getBlocksDocsLoaderCode(sources) {
  // A file that documents several elements is imported once.
  const files = [...new Set(sources.map((source) => source.path))];
  const imports = files.map(
    (file, index) =>
      `import docs${index} from ${JSON.stringify(`${file}?raw`)};`,
  );
  const items = sources.map(({ path: file, ...keys }) => {
    const fields = Object.entries(keys).map(
      ([key, value]) => `${key}: ${JSON.stringify(value)}, `,
    );
    return `  { ${fields.join('')}markdown: docs${files.indexOf(file)} },`;
  });
  return `/*
Don't change this file manually.
It is autogenerated by @kitconcept/volto-plate.
Instead, add or change the *.block.md files of the blocks.
*/
${imports.join('\n')}

export default [
${items.join('\n')}
];
`;
}

/*
 * Writes the docs loader module for the given folders and returns its path,
 * to be aliased as `load-blocks-docs`.
 */
function createBlocksDocsLoader(paths) {
  const loaderPath = path.join(
    os.tmpdir(),
    `volto-plate-blocks-docs-${crypto.randomUUID()}.js`,
  );
  fs.writeFileSync(loaderPath, getBlocksDocsLoaderCode(findBlocksDocs(paths)));
  return loaderPath;
}

module.exports = {
  createBlocksDocsLoader,
  findBlocksDocs,
  getBlocksDocsLoaderCode,
  parseFrontmatter,
};
